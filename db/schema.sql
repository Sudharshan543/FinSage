-- FinSage database schema
-- Finance document chunks for RAG and vector retrieval

CREATE COLUMN TABLE FINSAGE_DOCUMENT_CHUNKS (
    CHUNK_ID NVARCHAR(100) PRIMARY KEY,
    DOC_TYPE NVARCHAR(50) NOT NULL,
    CATEGORY NVARCHAR(100),
    REGION NVARCHAR(50),
    SOURCE_NAME NVARCHAR(255),
    EFFECTIVE_DATE DATE,
    ACCESS_LEVEL NVARCHAR(50),
    CHUNK_TEXT NCLOB NOT NULL,
    EMBEDDING REAL_VECTOR(1536)
);

-- FinSage invoice records

CREATE COLUMN TABLE FINSAGE_INVOICES (
    INVOICE_ID NVARCHAR(100) PRIMARY KEY,
    VENDOR_NAME NVARCHAR(255) NOT NULL,
    VENDOR_ID NVARCHAR(100),
    INVOICE_NUMBER NVARCHAR(100) NOT NULL,
    PO_NUMBER NVARCHAR(100),
    PO_APPROVED_AMOUNT DECIMAL(15,2),
    INVOICE_DATE DATE,
    DUE_DATE DATE,
    CURRENCY NVARCHAR(10),
    INVOICE_AMOUNT DECIMAL(15,2),
    TAX_AMOUNT DECIMAL(15,2),
    PAYMENT_STATUS NVARCHAR(50),
    REGION NVARCHAR(50),
    TRIAGE_STATUS NVARCHAR(50),
    FLAG_REASON NCLOB,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Invoice flag history

CREATE COLUMN TABLE DBADMIN.FINSAGE_INVOICE_FLAGS (
    CASE_REF NVARCHAR(36) PRIMARY KEY,
    INVOICE_ID NVARCHAR(100) NOT NULL,
    REASON NCLOB NOT NULL,
    STATUS NVARCHAR(30) NOT NULL,
    FLAGGED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- FinSage expense compliance exceptions

CREATE COLUMN TABLE FINSAGE_EXPENSE_EXCEPTIONS (
    EXCEPTION_ID NVARCHAR(100) PRIMARY KEY,
    EMPLOYEE_ID NVARCHAR(100),
    EMPLOYEE_NAME NVARCHAR(255),
    EXPENSE_CATEGORY NVARCHAR(100),
    EXPENSE_AMOUNT DECIMAL(15,2),
    CURRENCY NVARCHAR(10),
    EXPENSE_DATE DATE,
    REGION NVARCHAR(50),
    POLICY_REFERENCE NVARCHAR(255),
    EXCEPTION_REASON NCLOB,
    SEVERITY NVARCHAR(30),
    APPROVAL_STATUS NVARCHAR(50),
    NIGHTS INTEGER,
    DAYS INTEGER,
    RECEIPT_STATUS NVARCHAR(20),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- FinSage agent execution traces

CREATE COLUMN TABLE FINSAGE_AGENT_TRACES (
    TRACE_ID NVARCHAR(36) PRIMARY KEY,
    REQUEST_TYPE NVARCHAR(100) NOT NULL,
    REQUEST_SUMMARY NCLOB NOT NULL,
    STARTED_AT TIMESTAMP NOT NULL,
    FINISHED_AT TIMESTAMP,
    STATUS NVARCHAR(30) NOT NULL,
    DECISION NVARCHAR(100),
    STAGES_JSON NCLOB NOT NULL
);